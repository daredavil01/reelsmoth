// Build catalog/index.json from the frontmatter of catalog/<category>/<id>.md.
// This index is what the video-director skill reads to pick components.
// Also rewrites the table between the INDEX markers in catalog/README.md.
//
//   npm run catalog            # write index.json + README table
//   npm run catalog -- --check # exit 1 if anything is missing or stale
import {existsSync, readdirSync, readFileSync, statSync, writeFileSync} from 'node:fs';
import {join, relative} from 'node:path';

const ROOT = join(import.meta.dirname, '..');
const CATALOG = join(ROOT, 'catalog');
const REQUIRED = ['id', 'category', 'engine', 'component', 'duration', 'params', 'best-for', 'source', 'licence', 'preview'] as const;
const ENGINES = ['remotion', 'hyperframes', 'manim', 'moviepy'];

type Entry = {
  id: string;
  category: string;
  engine: string;
  component: string;
  composition?: string;
  duration: string;
  params: string[];
  bestFor: string[];
  source: string;
  licence: string;
  preview: string | null;
  doc: string;
  useWhen: string;
};

/** Minimal frontmatter parser: `key: value` and `key: [a, b]` lines only. */
const parseFrontmatter = (text: string, file: string): Record<string, string | string[]> => {
  const m = text.match(/^---\n([\s\S]*?)\n---/);
  if (!m) throw new Error(`${file}: no frontmatter`);
  const out: Record<string, string | string[]> = {};
  for (const line of m[1].split('\n')) {
    const kv = line.match(/^([\w-]+):\s*(.*?)\s*(#.*)?$/);
    if (!kv) continue;
    const [, key, raw] = kv;
    out[key] = raw.startsWith('[') ? raw.slice(1, -1).split(',').map((s) => s.trim()).filter(Boolean) : raw;
  }
  return out;
};

const problems: string[] = [];
const entries: Entry[] = [];

for (const category of readdirSync(CATALOG).sort()) {
  const dir = join(CATALOG, category);
  if (!statSync(dir).isDirectory()) continue;
  for (const name of readdirSync(dir).filter((f) => f.endsWith('.md')).sort()) {
    const file = join(dir, name);
    const rel = relative(ROOT, file);
    const text = readFileSync(file, 'utf8');
    const fm = parseFrontmatter(text, rel);
    for (const k of REQUIRED) if (!fm[k] || (Array.isArray(fm[k]) && fm[k].length === 0)) problems.push(`${rel}: missing ${k}`);
    const str = (k: string) => (typeof fm[k] === 'string' ? (fm[k] as string) : '');
    const list = (k: string) => (Array.isArray(fm[k]) ? (fm[k] as string[]) : []);

    if (str('id') !== name.replace(/\.md$/, '')) problems.push(`${rel}: id "${str('id')}" does not match the file name`);
    if (str('category') !== category) problems.push(`${rel}: category "${str('category')}" does not match its folder`);
    if (!ENGINES.includes(str('engine'))) problems.push(`${rel}: unknown engine "${str('engine')}"`);
    const component = str('component');
    if (component.startsWith('src/') && !existsSync(join(ROOT, component))) problems.push(`${rel}: component ${component} not found`);
    const preview = str('preview');
    const previewPath = join(dir, preview);
    if (preview && !existsSync(previewPath)) problems.push(`${rel}: preview ${preview} not rendered (scripts/catalog-previews.sh ${str('id')})`);
    const useWhen = text.match(/\*\*Use when:\*\*\s*(.+)/)?.[1].trim() ?? '';

    entries.push({
      id: str('id'),
      category,
      engine: str('engine'),
      component,
      composition: str('composition') || undefined,
      duration: str('duration'),
      params: list('params'),
      bestFor: list('best-for'),
      source: str('source'),
      licence: str('licence'),
      preview: preview && existsSync(previewPath) ? relative(ROOT, previewPath) : null,
      doc: rel,
      useWhen,
    });
  }
}

const ids = new Set<string>();
for (const e of entries) {
  if (ids.has(e.id)) problems.push(`duplicate id ${e.id}`);
  ids.add(e.id);
}

const index = JSON.stringify({$comment: 'Generated by scripts/build-catalog.ts from catalog/<category>/<id>.md. Do not edit.', count: entries.length, entries}, null, 2) + '\n';
const table = [
  '| id | Category | Component | Use when | Preview |',
  '| --- | --- | --- | --- | --- |',
  ...entries.map((e) => `| [${e.id}](${relative(CATALOG, join(ROOT, e.doc))}) | ${e.category} | \`${e.component}\` | ${e.useWhen} | ${e.preview ? `![${e.id}](${relative(CATALOG, join(ROOT, e.preview))})` : '-'} |`),
].join('\n');
const readmePath = join(CATALOG, 'README.md');
const readme = readFileSync(readmePath, 'utf8');
const START = '<!-- INDEX:START -->';
const END = '<!-- INDEX:END -->';
if (!readme.includes(START)) problems.push('catalog/README.md: missing INDEX markers');
const newReadme = readme.replace(new RegExp(`${START}[\\s\\S]*?${END}`), `${START}\n${table}\n${END}`);

const indexPath = join(CATALOG, 'index.json');
if (process.argv.includes('--check')) {
  if (!existsSync(indexPath) || readFileSync(indexPath, 'utf8') !== index) problems.push('catalog/index.json is stale: run npm run catalog');
  if (readme !== newReadme) problems.push('catalog/README.md table is stale: run npm run catalog');
} else {
  writeFileSync(indexPath, index);
  writeFileSync(readmePath, newReadme);
}

for (const p of problems) console.error(`FAIL  ${p}`);
console.log(`${entries.length} entries, ${entries.filter((e) => e.preview).length} with previews${problems.length ? `, ${problems.length} problems` : ''}`);
process.exit(problems.length ? 1 : 0);
